# --- textures ---------------------------------------------------------------------------------

QUAD = [(0, 0, 0), (2, 0, 0), (2, 1, 0), (0, 1, 0)]
QUAD_UV = [(0, 0), (0.5, 0), (0.5, 0.25), (0, 0.25)]
QUAD_FACES = [(0, 1, 2), (0, 2, 3)]
FLIPPED = [[u, 1 - v] for u, v in QUAD_UV]
TEAL = [20, 180, 170]


def textured(name, ref, files, expect_textured=True, extra=None):
    quad = trimesh(QUAD, QUAD_FACES, uvs=QUAD_UV, mats=[("Tex", [0, 1])])
    want = {"name": "Tex", "textured": expect_textured}
    want.update({"color": [1, 1, 1, 1], "pixel": TEAL} if expect_textured else {"color": lin(RED)})
    case(FMT, name, {"quad.3ds": model(material("Tex", color24(RED), texmap(ref)), obj("Quad", quad)), **files},
         {"spec": SPEC + extra, "source": SRC, "triangles": 2, "area": 2.0, "bounds": bounds(QUAD),
          "uvs_include": FLIPPED, "materials": [want]})


textured("texture", "teal.png", {"teal.png": png(TEAL)}, extra=": a texture map (MAT_TEXMAP > MAP_FILE); V flipped")
textured("texture_name_case", "TEAL.PNG", {"teal.png": png(TEAL)},
         extra=": an 8.3 upper-case texture name for a lower-case file")
textured("texture_absolute_path", "C:\\3DSMAX\\MAPS\\teal.png", {"maps/teal.png": png(TEAL)},
         extra=": a texture named by the absolute path it had on the author's machine")
textured("texture_missing", "gone.png", {}, expect_textured=False,
         extra=": a texture that isn't there leaves the diffuse color")

